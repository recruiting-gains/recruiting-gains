const FALLBACK = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'];

/** Space is blank, so trimming would erase it. Give it a fixed width instead. */
const SPACE_WIDTH = 2;

/**
 * Turn a 7-row string glyph into columns of booleans, with empty outer columns
 * trimmed so the font reads as proportional rather than monospaced.
 */
function compile(rows) {
  const cols = [];
  for (let x = 0; x < 5; x++) {
    cols.push(rows.map((r) => r[x] === '#'));
  }
  let start = 0;
  let end = cols.length - 1;
  while (start <= end && cols[start].every((v) => !v)) start++;
  while (end >= start && cols[end].every((v) => !v)) end--;
  if (start > end) return Array.from({ length: SPACE_WIDTH }, () => new Array(7).fill(false));
  return cols.slice(start, end + 1);
}

const GLYPHS = new Map();
for (const [ch, rows] of Object.entries(RAW)) GLYPHS.set(ch, compile(rows));
const FALLBACK_GLYPH = compile(FALLBACK);

/**
 * Render a string into an array of columns; each column is 7 booleans,
 * top (Sunday) to bottom (Saturday). One blank column between glyphs.
 */
export function renderText(text) {
  const chars = [...text.toUpperCase().replace(/<3/g, '♥')];
  const out = [];
  chars.forEach((ch, i) => {
    const glyph = GLYPHS.get(ch) ?? FALLBACK_GLYPH;
    if (i > 0) out.push(new Array(7).fill(false));
    for (const col of glyph) out.push(col.slice());
  });
  return out;
}

/** Width in grid columns that `text` would occupy. */
export function measureText(text) {
  return renderText(text).length;
}
